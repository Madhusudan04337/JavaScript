// The replace() method searches a string for a specified value or a regular expression,
// and returns a new string where the first match is replaced.
// The original string is not changed.

let str = "Mind, Power, Soul";

// Replaces the first occurrence of "Power" with "Space"
let part = str.replace("Power", "Space");

console.log(part);

/*
Expected Output:
Mind, Space, Soul
*/