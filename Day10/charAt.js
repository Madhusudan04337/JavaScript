// The charAt() method returns the character at a specified index in a string.
// String indexing is zero-based.

let company = 'Developer';
let moto = 'Code is the best way to learn and\n'+
'experience Computer Science.';

// Print the strings as they are
console.log(company);
console.log(moto);

// As string index starts from zero
// It will return first character of string
console.log(company.charAt(0));

// It will return character at the 5th index
console.log(moto.charAt(5));

/*
Expected Output:
Developer
Code is the best way to learn and
experience Computer Science.
D
i
*/